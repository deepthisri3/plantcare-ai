import React, { useState } from 'react';
import { 
  CheckCircle, 
  AlertTriangle, 
  XCircle, 
  HelpCircle, 
  ShieldAlert, 
  RotateCcw, 
  Sun, 
  Activity, 
  CheckCheck, 
  Compass, 
  Info,
  FileText,
  Printer,
  Download,
  Check
} from 'lucide-react';
import './PlantResult.css';

export default function PlantResult({ 
  result, 
  previewUrl, 
  onReset, 
  onTakeMeOutside 
}) {
  const { analysis, model_used, disclaimer } = result;

  const [downloadedMd, setDownloadedMd] = useState(false);
  const [observationDate] = useState(() => 
    new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' })
  );

  const healthStatus = analysis?.health_status || 'Uncertain';
  const confidencePercent = Math.round((analysis?.confidence || 0.8) * 100);

  const handleExportMarkdown = () => {
    const dateStr = new Date().toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    });

    const mdContent = `# Touch Grass — Field Observation Report

**Plant:** ${analysis?.plant_name || 'Plant Observation'}  
**Botanical Name:** *${analysis?.scientific_name || 'Unknown'}*  
**Date of Observation:** ${dateStr}  
**Identification Certainty:** ${confidencePercent}%  
**Model Used:** ${model_used || 'Gemma 3'}  

---

## 🌿 Health Overview
- **Health Status:** ${analysis?.health_status || 'Uncertain'}
- **Severity Level:** ${analysis?.severity || 'None'}
- **Suspected Condition:** ${analysis?.possible_disease || 'No obvious disease detected'}
- **Expert Attention Recommended:** ${analysis?.needs_expert_attention ? 'Yes' : 'No'}

## 📝 Summary
> "${analysis?.summary || 'No summary provided.'}"

## 🔍 Visible Symptoms
${analysis?.visible_symptoms && analysis.visible_symptoms.length > 0
  ? analysis.visible_symptoms.map(s => `- ${s}`).join('\n')
  : '- No adverse lesions, wilting, or pest symptoms visually observed.'}

## ❓ Possible Causes
${analysis?.possible_causes && analysis.possible_causes.length > 0
  ? analysis.possible_causes.map(c => `- ${c}`).join('\n')
  : '- Standard natural or seasonal growth factors.'}

## 🌱 Recommended Care Actions
${analysis?.recommendations && analysis.recommendations.length > 0
  ? analysis.recommendations.map((r, i) => `${i + 1}. ${r}`).join('\n')
  : '- Continue regular species-appropriate care.'}

## ☀️ Field Notes & Habitat
${analysis?.environmental_observations && analysis.environmental_observations.length > 0
  ? analysis.environmental_observations.map(n => `- ${n}`).join('\n')
  : '- No environmental anomalies noted.'}

---
### ⚠️ Disclaimer
${disclaimer || 'AI-generated plant health assessments are informational only. For serious plant disease or agricultural decisions, consult a qualified expert.'}

*Generated by Touch Grass — Open-Weight AI Plant Companion*
`;

    const blob = new Blob([mdContent], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    const safeName = (analysis?.plant_name || 'plant').toLowerCase().replace(/[^a-z0-9]+/g, '-');
    link.href = url;
    link.download = `field-card-${safeName}.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);

    setDownloadedMd(true);
    setTimeout(() => setDownloadedMd(false), 2500);
  };

  const handleExportPDF = () => {
    window.print();
  };

  // Accessible visual indicators for health status
  const getHealthBadge = (status) => {
    switch (status) {
      case 'Healthy':
        return {
          label: 'Healthy',
          icon: CheckCircle,
          className: 'health-badge-healthy',
          desc: 'No major distress or pathogens observed. Plant appears vigorous.',
        };
      case 'Needs Attention':
        return {
          label: 'Needs Attention',
          icon: AlertTriangle,
          className: 'health-badge-attention',
          desc: 'Mild distress, minor spot signs, or slight environmental stress observed.',
        };
      case 'Unhealthy':
        return {
          label: 'Unhealthy / Diseased',
          icon: XCircle,
          className: 'health-badge-unhealthy',
          desc: 'Pronounced symptoms, pathogen lesions, or damage detected.',
        };
      default:
        return {
          label: 'Uncertain Health',
          icon: HelpCircle,
          className: 'health-badge-uncertain',
          desc: 'Image lighting or angle limits confident diagnostic determination.',
        };
    }
  };

  const badge = getHealthBadge(healthStatus);
  const StatusIcon = badge.icon;

  return (
    <div className="plant-result-container animate-fade-in" id="results">
      <div className="container-narrow">
        <div className="result-main-card natural-card">
          
          {/* Print only header for PDF generation */}
          <div className="print-only-header">
            <div>
              <span className="print-brand-title">Touch Grass — Plant Field Card</span>
              <p className="print-brand-sub">Open-Weight AI Plant Health Observation (Gemma 3)</p>
            </div>
            <div className="print-date">
              {observationDate}
            </div>
          </div>

          {/* Header */}
          <div className="result-top-banner">
            <span className="result-field-tag">Field Observation Complete</span>
            <span className="result-model-badge">Model: {model_used || 'Gemma 3'}</span>
          </div>

          {/* Export Action Bar */}
          <div className="export-action-bar">
            <span className="export-bar-label">
              <Download size={14} />
              <span>Export Field Card:</span>
            </span>
            <div className="export-buttons-group">
              <button
                type="button"
                className="btn-export-action"
                onClick={handleExportMarkdown}
                title="Download Field Card as Markdown (.md)"
              >
                {downloadedMd ? (
                  <>
                    <Check size={14} className="export-success-icon" />
                    <span>Downloaded!</span>
                  </>
                ) : (
                  <>
                    <FileText size={14} />
                    <span>Download Markdown (.md)</span>
                  </>
                )}
              </button>

              <button
                type="button"
                className="btn-export-action"
                onClick={handleExportPDF}
                title="Print or Save Field Card as PDF"
              >
                <Printer size={14} />
                <span>Save as PDF</span>
              </button>
            </div>
          </div>

          <div className="result-headline-section">
            <div className="result-title-group">
              <span className="result-intro-sub">Here&apos;s what you found</span>
              <h2 className="plant-common-name">{analysis?.plant_name || 'Plant Observation'}</h2>
              <p className="plant-scientific-name">
                <em>{analysis?.scientific_name || 'Botanical name unconfirmed'}</em>
              </p>
            </div>

            <div className="confidence-pill" title="AI Identification Certainty Score">
              <span className="confidence-label">Certainty</span>
              <span className="confidence-number">{confidencePercent}%</span>
            </div>
          </div>

          {/* Plant photo + Health Status summary row */}
          <div className="result-overview-grid">
            {previewUrl && (
              <div className="result-image-box">
                <img src={previewUrl} alt={analysis?.plant_name} className="result-thumb" />
                <span className="result-image-badge">Your Field Photo</span>
              </div>
            )}

            <div className={`health-status-card ${badge.className}`}>
              <div className="health-card-header">
                <div className="health-status-icon-wrap">
                  <StatusIcon size={26} />
                </div>
                <div>
                  <span className="health-card-label">Health Status</span>
                  <h3 className="health-card-title">{badge.label}</h3>
                </div>
              </div>
              <p className="health-status-desc">{badge.desc}</p>
              
              <div className="severity-bar-wrap">
                <span className="severity-tag">Severity: <strong>{analysis?.severity || 'None'}</strong></span>
                {analysis?.needs_expert_attention && (
                  <span className="expert-flag">
                    <ShieldAlert size={14} /> Expert Recommended
                  </span>
                )}
              </div>
            </div>
          </div>

          {/* Summary */}
          {analysis?.summary && (
            <div className="result-summary-block">
              <p className="summary-text">&ldquo;{analysis.summary}&rdquo;</p>
            </div>
          )}

          {/* Possible Disease */}
          <div className="result-section-box">
            <h3 className="section-box-title">
              <Activity size={18} className="box-icon" />
              <span>Possible Condition or Pathogen</span>
            </h3>
            <div className="disease-box-content">
              <p className="disease-name-text">
                {analysis?.possible_disease || 'No obvious disease detected from this image.'}
              </p>
            </div>
          </div>

          {/* Visible Symptoms */}
          <div className="result-section-box">
            <h3 className="section-box-title">
              <EyeIcon size={18} className="box-icon" />
              <span>Visible Symptoms</span>
            </h3>
            {analysis?.visible_symptoms && analysis.visible_symptoms.length > 0 ? (
              <div className="symptoms-chip-list">
                {analysis.visible_symptoms.map((symptom, idx) => (
                  <div key={idx} className="symptom-chip">
                    <span className="symptom-bullet">•</span>
                    <span>{symptom}</span>
                  </div>
                ))}
              </div>
            ) : (
              <p className="neutral-note">No adverse lesions, wilting, or pest symptoms visually observed.</p>
            )}
          </div>

          {/* Possible Causes */}
          {analysis?.possible_causes && analysis.possible_causes.length > 0 && (
            <div className="result-section-box">
              <h3 className="section-box-title">
                <HelpCircle size={18} className="box-icon" />
                <span>Possible Causes</span>
              </h3>
              <ul className="causes-list">
                {analysis.possible_causes.map((cause, idx) => (
                  <li key={idx} className="cause-item">
                    <span className="cause-marker">→</span>
                    <span>{cause}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}

          {/* What You Can Do (Recommendations) */}
          <div className="result-section-box">
            <h3 className="section-box-title">
              <CheckCheck size={18} className="box-icon" />
              <span>What You Can Do</span>
            </h3>
            {analysis?.recommendations && analysis.recommendations.length > 0 ? (
              <div className="recommendations-list">
                {analysis.recommendations.map((rec, idx) => (
                  <div key={idx} className="recommendation-card">
                    <span className="rec-num">{idx + 1}</span>
                    <span className="rec-text">{rec}</span>
                  </div>
                ))}
              </div>
            ) : (
              <p className="neutral-note">Continue regular care suitable for this species.</p>
            )}
          </div>

          {/* Field Notes (Environmental observations) */}
          {analysis?.environmental_observations && analysis.environmental_observations.length > 0 && (
            <div className="result-section-box field-notes-box">
              <h3 className="section-box-title">
                <Sun size={18} className="box-icon" />
                <span>Field Notes &amp; Habitat</span>
              </h3>
              <ul className="field-notes-list">
                {analysis.environmental_observations.map((note, idx) => (
                  <li key={idx} className="field-note-item">
                    <span>{note}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}

          {/* Mandatory Disclaimer */}
          <div className="disclaimer-callout" role="note">
            <Info size={16} className="disclaimer-icon" />
            <p className="disclaimer-text">
              {disclaimer || 'AI-generated identification and health assessments are informational and may be inaccurate. For serious plant disease or agricultural decisions, consult a qualified expert.'}
            </p>
          </div>

          {/* ENCOURAGE USERS TO GO BACK OUTSIDE */}
          <div className="return-outside-banner">
            <div className="return-outside-content">
              <h3 className="return-outside-title">Now go look again.</h3>
              <p className="return-outside-quote">
                AI can tell you what it sees.
                <br />
                <strong>You get to experience the real thing.</strong>
              </p>
            </div>

            <div className="return-outside-buttons">
              <button 
                type="button" 
                className="btn-outline return-btn-find"
                onClick={onReset}
              >
                <RotateCcw size={16} />
                <span>Find Another Plant</span>
              </button>

              <button 
                type="button" 
                className="btn-primary return-btn-outside"
                onClick={onTakeMeOutside}
              >
                <Compass size={18} />
                <span>Take Me Outside</span>
              </button>
            </div>
          </div>

        </div>
      </div>
    </div>
  );
}

function EyeIcon({ size = 18, className = '' }) {
  return (
    <svg 
      width={size} 
      height={size} 
      viewBox="0 0 24 24" 
      fill="none" 
      stroke="currentColor" 
      strokeWidth="2" 
      strokeLinecap="round" 
      strokeLinejoin="round" 
      className={className}
    >
      <path d="M2 12s3-7 10-7 10 7 10 7-3 7-10 7-10-7-10-7Z" />
      <circle cx="12" cy="12" r="3" />
    </svg>
  );
}
